"""Draws the moon's face (bright highlands, dark seas, a few bright craters) as a small
greyscale texture and writes it to ui/moon_texture.c. The screen lights this one image
differently for each phase, so no per-phase pictures are needed.

It is a hand-placed approximation of the near side, not a photograph.

Run from the firmware folder with the server's Python (needs Pillow):
    ../server/.venv/bin/python tools/make_moon.py
"""

import random
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

SIZE, SCALE = 64, 6  # drawn large, then shrunk for smooth edges
BIG = SIZE * SCALE
random.seed(7)

# (x, y, radius_x, radius_y, brightness) with x right and y down, each from -1 to 1
SEAS = [
    (-0.62, -0.18, 0.30, 0.46, 96),  # Oceanus Procellarum
    (-0.26, -0.46, 0.30, 0.26, 92),  # Mare Imbrium
    (0.22, -0.38, 0.19, 0.19, 98),  # Mare Serenitatis
    (0.40, -0.10, 0.22, 0.19, 94),  # Mare Tranquillitatis
    (0.69, -0.26, 0.10, 0.12, 90),  # Mare Crisium
    (0.62, 0.10, 0.13, 0.16, 104),  # Mare Fecunditatis
    (0.42, 0.27, 0.09, 0.09, 104),  # Mare Nectaris
    (-0.14, 0.36, 0.22, 0.17, 102),  # Mare Nubium
    (-0.48, 0.38, 0.11, 0.11, 98),  # Mare Humorum
    (0.02, -0.80, 0.42, 0.07, 120),  # Mare Frigoris
    (0.04, -0.12, 0.10, 0.10, 112),  # Mare Vaporum
]
BRIGHT = [(-0.12, 0.70, 0.050), (-0.33, -0.13, 0.040), (-0.69, -0.38, 0.030), (-0.47, -0.08, 0.028)]


def to_px(v):
    return (v + 1) / 2 * BIG


image = Image.new("L", (BIG, BIG), 205)
draw = ImageDraw.Draw(image)
for x, y, rx, ry, shade in SEAS:
    draw.ellipse([to_px(x - rx), to_px(y - ry), to_px(x + rx), to_px(y + ry)], fill=shade)
image = image.filter(ImageFilter.GaussianBlur(BIG * 0.035))

draw = ImageDraw.Draw(image)
for _ in range(260):  # small craters: a darker dot with a lighter rim
    x, y = random.uniform(-0.95, 0.95), random.uniform(-0.95, 0.95)
    if x * x + y * y > 0.9:
        continue
    r = random.uniform(0.008, 0.028)
    box = [to_px(x - r), to_px(y - r), to_px(x + r), to_px(y + r)]
    base = image.getpixel((int(to_px(x)), int(to_px(y))))
    draw.ellipse(box, fill=max(0, base - random.randint(10, 26)), outline=min(255, base + 18))
for x, y, r in BRIGHT:  # young craters with bright rays
    draw.ellipse([to_px(x - r), to_px(y - r), to_px(x + r), to_px(y + r)], fill=250)
    for _ in range(9):
        angle, reach = random.uniform(0, 6.283), random.uniform(0.10, 0.30)
        import math

        draw.line(
            [to_px(x), to_px(y), to_px(x + math.cos(angle) * reach), to_px(y + math.sin(angle) * reach)],
            fill=228,
            width=max(1, SCALE // 3),
        )
image = image.filter(ImageFilter.GaussianBlur(BIG * 0.006)).resize((SIZE, SIZE), Image.LANCZOS)

values = list(image.getdata())
rows = [", ".join(f"{v:3d}" for v in values[i : i + 16]) for i in range(0, len(values), 16)]
out = Path(__file__).resolve().parents[1] / "ui" / "moon_texture.c"
out.write_text(
    "/* Generated by tools/make_moon.py. A 64x64 greyscale map of the moon's face. */\n"
    "#include <stdint.h>\n\n"
    f"const uint8_t moon_texture[{SIZE * SIZE}] = {{\n    " + ",\n    ".join(rows) + ",\n};\n"
)
image.resize((256, 256), Image.NEAREST).save(Path(__file__).resolve().parents[1] / "build" / "moon_texture_preview.png")
print("wrote", out)
